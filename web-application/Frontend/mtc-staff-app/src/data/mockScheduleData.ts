// Helper to get active schedules by year (CE)
export function getScheduleDataByYear(yearCe: number): MonthSchedule[] {
  if (typeof window !== "undefined") {
    const saved = localStorage.getItem(`mtc_schedule_${yearCe}`);
    if (saved) {
      try {
        const parsed = JSON.parse(saved);
        if (Array.isArray(parsed) && parsed.length >= 12) {
          return parsed;
        }
      } catch (e) {
        console.warn("Failed to parse saved schedule:", e);
      }
    }
  }
  return yearCe === 2027 ? MOCK_SCHEDULES_2027 : MOCK_SCHEDULES_2026;
}

export function saveScheduleDataByYear(yearCe: number, data: MonthSchedule[]) {
  if (typeof window !== "undefined") {
    localStorage.setItem(`mtc_schedule_${yearCe}`, JSON.stringify(data));
  }
}

/**
 * Resets all schedule data completely starting from 0 (empty services across all months).
 */
export function resetScheduleToZero(yearCe?: number): MonthSchedule[] {
  const empty2026 = createEmptyYearSchedule(2026);
  const empty2027 = createEmptyYearSchedule(2027);

  if (typeof window !== "undefined") {
    localStorage.setItem("mtc_schedule_2026", JSON.stringify(empty2026));
    localStorage.setItem("mtc_schedule_2027", JSON.stringify(empty2027));
  }

  return yearCe === 2027 ? empty2027 : empty2026;
}

