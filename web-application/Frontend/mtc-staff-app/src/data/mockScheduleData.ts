export interface DeaconInfo {
  id: number;
  name: string;
  department: string;
  role: string;
  phone?: string;
}

export interface ServiceDuty {
  id: string;
  dateStr: string; // e.g., "2026-04-01"
  dayDisplay: string; // e.g. "1", "8", "พฤ.3", "ศ.4", "อา.5"
  dayOfWeek: string; // "พุธ", "พฤหัสบดี", "ศุกร์", "เสาร์", "อาทิตย์"
  specialEvent?: string; // "มหาสนิท", "ศุกร์ประเสริฐ", "วันอีสเตอร์", "วันแม่", etc.
  specialEventType?: "communion" | "holy-week" | "special-sunday" | "camp" | "normal";
  topic: string; // เรื่อง/ประเด็นหลัก
  scripture: string; // ข้อพระธรรม
  preacher: string; // นมัสการใหญ่ (ผู้เทศนา)
  translator: string; // ผู้แปล
  worshipLeader: string; // ผู้นำ
  worshipTranslator: string; // แปลนำ
  offeringUpper: number[]; // มน.ถือกองถวายบน (8 positions)
  offeringLower: number[]; // มน.ถือกองถวายล่าง (4 positions)
  servingUpperRoom?: string; // มน.ร่วมนำนมัสการ & รับใช้ ห้องบน
  servingLowerRoom?: string; // มน.ร่วมนำนมัสการ & รับใช้ ห้องล่าง/ชั้น4
  servingMainGate?: string; // มน.ร่วมนำนมัสการ & รับใช้ ประตูใหญ่
  unavailableNotes?: string; // เช่น "5, 15 ไม่ได้", "13 (ลา มน)"
}

export interface MonthSchedule {
  monthKey: number; // 1 - 12
  monthNameTh: string; // "มกราคม", "กุมภาพันธ์", etc.
  monthShortTh: string; // "ม.ค.", "ก.พ.", etc.
  yearBe: number; // 2569 / 2570
  yearCe: number; // 2026 / 2027
  themeBanner?: string; // e.g. "ศจ.บุญนาม / ศจ.กัญจน์"
  baptismNotice?: string; // e.g. "บัพติศมา สี่ มิชาริ"
  services: ServiceDuty[];
}

